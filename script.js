let currentLang = localStorage.getItem('lang') || 'tr';

function applyLang(lang){
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(translations[lang][key] !== undefined){
      el.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  resetTypewriter();
}

/* ---------- page routing ---------- */
function goTo(page){
  document.querySelectorAll('.page').forEach(p => p.classList.remove('active'));
  document.getElementById('page-' + page).classList.add('active');
  document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
  document.querySelector('.nav-link[data-page="' + page + '"]').classList.add('active');
  window.scrollTo(0,0);
  history.replaceState(null, '', '#' + page);
}

window.addEventListener('DOMContentLoaded', () => {
  const hash = window.location.hash.replace('#','');
  if(hash === 'contact') goTo('contact');
  applyLang(currentLang);
  const year = new Date().getFullYear();
  ['year', 'year-contact'].forEach(id => {
    const el = document.getElementById(id);
    if(el) el.textContent = year;
  });
});

/* ---------- typewriter effect for hero ---------- */
const typedEl = document.getElementById('typedText');
let pIndex = 0, cIndex = 0, deleting = false, typeTimer = null;

function typeLoop(){
  const list = phrases[currentLang];
  const current = list[pIndex];
  if(!deleting){
    cIndex++;
    typedEl.textContent = '"' + current.slice(0, cIndex) + '"';
    if(cIndex === current.length){
      deleting = true;
      typeTimer = setTimeout(typeLoop, 1800);
      return;
    }
  } else {
    cIndex--;
    typedEl.textContent = '"' + current.slice(0, cIndex) + '"';
    if(cIndex === 0){
      deleting = false;
      pIndex = (pIndex + 1) % list.length;
    }
  }
  typeTimer = setTimeout(typeLoop, deleting ? 35 : 60);
}

function resetTypewriter(){
  clearTimeout(typeTimer);
  pIndex = 0; cIndex = 0; deleting = false;
  typedEl.textContent = '';
  typeLoop();
}
