const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const mobileQuery = window.matchMedia("(max-width: 768px)");
const loader = document.querySelector(".loader");
const heroGrid = document.querySelector(".hero-grid");
const menu = document.querySelector(".site-menu");
const menuToggle = document.querySelector(".menu-toggle");
const drawer = document.querySelector(".contact-drawer");
const drawerBackdrop = document.querySelector(".drawer-backdrop");
let currentLang = "tr";
let lastFocused = null;
let isMobile = mobileQuery.matches;
let heroTimers = [];

try {
  const savedLang = localStorage.getItem("lang");
  if (savedLang === "tr" || savedLang === "en") currentLang = savedLang;
} catch (error) {
  currentLang = "tr";
}

function applyLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = lang === "tr" ? "Seçkin Bulgur | Software Developer" : "Seckin Bulgur | Software Developer";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[lang][element.dataset.i18n];
    if (value === undefined) return;
    const textNode = Array.from(element.childNodes).find((node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim());
    if (textNode && element.children.length) textNode.textContent = value;
    else element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = translations[lang][element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = translations[lang][element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  try {
    localStorage.setItem("lang", lang);
  } catch (error) {
    return;
  }
}

function syncBodyLock() {
  const locked = menu.classList.contains("is-open") || drawer.classList.contains("is-open") || !loader.classList.contains("is-done");
  document.body.classList.toggle("is-locked", locked);
}

function closeMenu() {
  menu.classList.remove("is-open");
  menu.setAttribute("aria-hidden", "true");
  menuToggle.setAttribute("aria-expanded", "false");
  syncBodyLock();
}

function openMenu() {
  closeContact(false);
  menu.classList.add("is-open");
  menu.setAttribute("aria-hidden", "false");
  menuToggle.setAttribute("aria-expanded", "true");
  syncBodyLock();
  const firstLink = menu.querySelector("a");
  window.setTimeout(() => firstLink.focus({ preventScroll: true }), 400);
}

function openContact() {
  lastFocused = document.activeElement;
  closeMenu();
  drawer.classList.add("is-open");
  drawerBackdrop.classList.add("is-open");
  drawer.setAttribute("aria-hidden", "false");
  syncBodyLock();
  window.setTimeout(() => drawer.querySelector(".drawer-close").focus({ preventScroll: true }), 650);
}

function closeContact(restoreFocus = true) {
  const wasOpen = drawer.classList.contains("is-open");
  drawer.classList.remove("is-open");
  drawerBackdrop.classList.remove("is-open");
  drawer.setAttribute("aria-hidden", "true");
  syncBodyLock();
  if (wasOpen && restoreFocus && lastFocused) lastFocused.focus({ preventScroll: true });
}

function buildHeroGrid() {
  heroTimers.forEach(window.clearTimeout);
  heroTimers = [];
  heroGrid.classList.remove("is-ready", "is-complete");
  heroGrid.replaceChildren();
  const count = mobileQuery.matches ? 18 : 36;
  const fragment = document.createDocumentFragment();
  for (let index = 0; index < count; index += 1) {
    const panel = document.createElement("div");
    panel.className = "hero-panel";
    panel.innerHTML = '<span class="panel-face panel-front"><i></i></span><span class="panel-face panel-back"></span>';
    fragment.appendChild(panel);
  }
  heroGrid.appendChild(fragment);
}

function revealHero() {
  loader.classList.add("is-done");
  syncBodyLock();
  const panels = Array.from(heroGrid.children);
  if (reducedMotion.matches) {
    heroGrid.classList.add("is-ready", "is-complete");
    panels.forEach((panel) => panel.classList.add("is-flipped"));
    document.querySelectorAll(".hero-line > span").forEach((line) => { line.style.transform = "none"; });
    document.querySelectorAll(".reveal-hero").forEach((element) => { element.style.opacity = "1"; });
    return;
  }
  heroTimers.push(window.setTimeout(() => heroGrid.classList.add("is-ready"), 100));
  panels.forEach((panel, index) => {
    const delay = 120 + (index % 6) * 45 + Math.random() * 450;
    heroTimers.push(window.setTimeout(() => panel.classList.add("is-flipped"), delay));
  });
  heroTimers.push(window.setTimeout(() => heroGrid.classList.add("is-complete"), 1800));
  if (window.gsap) {
    window.gsap.timeline({ delay: .45 })
      .to(".hero-line > span", { y: 0, duration: 1.25, stagger: .13, ease: "power4.out" })
      .to(".reveal-hero", { opacity: 1, y: 0, duration: .8, stagger: .1, ease: "power2.out" }, "-=.65");
  } else {
    document.querySelectorAll(".hero-line > span").forEach((line, index) => {
      line.style.transition = `transform 1s ${index * .12}s cubic-bezier(.22,1,.36,1)`;
      line.style.transform = "translateY(0)";
    });
    document.querySelectorAll(".reveal-hero").forEach((element) => {
      element.style.transition = "opacity .8s .5s";
      element.style.opacity = "1";
    });
  }
}

function initLoader() {
  document.body.classList.add("is-locked");
  const count = document.querySelector(".loader-count");
  if (reducedMotion.matches) {
    count.textContent = "100";
    revealHero();
    return;
  }
  const start = performance.now();
  function update(now) {
    const progress = Math.min((now - start) / 1150, 1);
    count.textContent = String(Math.floor(progress * 100)).padStart(2, "0");
    if (progress < 1) requestAnimationFrame(update);
    else window.setTimeout(revealHero, 120);
  }
  requestAnimationFrame(update);
}

function setActiveProject(index) {
  document.querySelectorAll(".project-item").forEach((item) => item.classList.toggle("active", Number(item.dataset.project) === index));
  document.querySelectorAll(".project-screen").forEach((screen) => screen.classList.toggle("active", Number(screen.dataset.screen) === index));
}

function initProjectObserver() {
  const items = document.querySelectorAll(".project-item");
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) setActiveProject(Number(entry.target.dataset.project));
    });
  }, { rootMargin: "-32% 0px -32% 0px", threshold: 0 });
  items.forEach((item) => {
    observer.observe(item);
    item.addEventListener("mouseenter", () => setActiveProject(Number(item.dataset.project)));
  });
}

function initServiceObserver() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => entry.target.classList.toggle("is-active", mobileQuery.matches && entry.isIntersecting));
  }, { rootMargin: "-42% 0px -42% 0px", threshold: 0 });
  document.querySelectorAll(".service-row").forEach((row) => observer.observe(row));
}

function initScrollAnimations() {
  if (!window.gsap || !window.ScrollTrigger || reducedMotion.matches) return;
  window.gsap.registerPlugin(window.ScrollTrigger);
  const reveal = (selector, options = {}) => {
    window.gsap.utils.toArray(selector).forEach((element) => {
      window.gsap.from(element, {
        y: options.y || 55,
        x: options.x || 0,
        opacity: options.opacity === undefined ? 0 : options.opacity,
        duration: options.duration || 1,
        ease: "power3.out",
        scrollTrigger: { trigger: element, start: options.start || "top 88%", once: true }
      });
    });
  };
  reveal(".section-index", { y: 20 });
  reveal(".about-heading", { y: 90, start: "top 85%" });
  reveal(".about-lead, .about-copy", { y: 45 });
  reveal(".stat", { y: 50 });
  reveal(".giant-heading", { x: -60, opacity: 0, duration: 1.3 });
  reveal(".section-title", { y: 70 });
  reveal(".service-row", { y: 30 });
  reveal(".experience-row", { y: 45 });
  reveal(".education-block", { y: 45 });
  reveal(".contact-main > *", { y: 35 });
  window.gsap.to(".hero-content", {
    y: 100,
    opacity: .25,
    ease: "none",
    scrollTrigger: { trigger: ".hero", start: "top top", end: "bottom top", scrub: true }
  });
  window.gsap.to(".orbit-one", { y: -130, rotation: 10, ease: "none", scrollTrigger: { trigger: ".contact-section", start: "top bottom", end: "bottom top", scrub: 1 } });
  window.gsap.to(".orbit-two", { y: 150, rotation: -12, ease: "none", scrollTrigger: { trigger: ".contact-section", start: "top bottom", end: "bottom top", scrub: 1 } });
  window.gsap.to(".orbit-three", { y: -90, rotation: 14, ease: "none", scrollTrigger: { trigger: ".contact-section", start: "top bottom", end: "bottom top", scrub: 1 } });
}

function initMagnetic() {
  if (!window.matchMedia("(hover: hover) and (pointer: fine)").matches || reducedMotion.matches) return;
  document.querySelectorAll(".magnetic").forEach((element) => {
    element.addEventListener("mousemove", (event) => {
      const rect = element.getBoundingClientRect();
      const x = event.clientX - rect.left - rect.width / 2;
      const y = event.clientY - rect.top - rect.height / 2;
      element.style.transform = `translate(${x * .16}px, ${y * .16}px)`;
    });
    element.addEventListener("mouseleave", () => { element.style.transform = ""; });
  });
}

function trapDrawerFocus(event) {
  if (event.key !== "Tab" || !drawer.classList.contains("is-open")) return;
  const focusable = Array.from(drawer.querySelectorAll("a[href], button:not([disabled])"));
  const first = focusable[0];
  const last = focusable[focusable.length - 1];
  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

document.querySelectorAll(".lang-btn").forEach((button) => button.addEventListener("click", () => applyLang(button.dataset.lang)));
menuToggle.addEventListener("click", () => menu.classList.contains("is-open") ? closeMenu() : openMenu());
document.querySelectorAll("[data-open-contact]").forEach((button) => button.addEventListener("click", openContact));
document.querySelectorAll("[data-close-contact]").forEach((button) => button.addEventListener("click", () => closeContact()));
document.querySelectorAll('a[href^="#"]').forEach((link) => link.addEventListener("click", closeMenu));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeMenu();
    closeContact();
  }
  trapDrawerFocus(event);
});
mobileQuery.addEventListener("change", (event) => {
  if (event.matches === isMobile) return;
  isMobile = event.matches;
  buildHeroGrid();
  revealHero();
});

applyLang(currentLang);
buildHeroGrid();
initLoader();
initProjectObserver();
initServiceObserver();
initScrollAnimations();
initMagnetic();
document.getElementById("year").textContent = new Date().getFullYear();
document.querySelector(".menu-year").textContent = new Date().getFullYear();
